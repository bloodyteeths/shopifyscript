-- Automation Rules Table
-- Stores custom automation rules and configurations
CREATE TABLE IF NOT EXISTS automation_rules (
  id SERIAL PRIMARY KEY,
  tenant_id VARCHAR(100) NOT NULL,
  rule_name VARCHAR(200) NOT NULL,
  automation_type VARCHAR(50) NOT NULL, -- 'bid_optimization', 'budget_allocation', 'keyword_expansion', etc.
  rule_config JSONB NOT NULL, -- Algorithm-specific configuration
  trigger_conditions JSONB NOT NULL, -- When to trigger the automation
  action_config JSONB NOT NULL, -- What actions to take
  schedule_config JSONB DEFAULT '{}', -- When to run (cron-like scheduling)
  is_active BOOLEAN DEFAULT true,
  priority INTEGER DEFAULT 5, -- 1 (highest) to 10 (lowest)
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  last_executed_at TIMESTAMP WITH TIME ZONE,
  execution_count INTEGER DEFAULT 0,
  
  UNIQUE(tenant_id, rule_name)
);

-- Custom Bid Strategies Table
-- Enterprise-specific custom bidding algorithms
CREATE TABLE IF NOT EXISTS custom_bid_strategies (
  id SERIAL PRIMARY KEY,
  tenant_id VARCHAR(100) NOT NULL,
  strategy_name VARCHAR(200) NOT NULL,
  strategy_description TEXT,
  algorithm_config JSONB NOT NULL, -- Custom algorithm parameters
  performance_targets JSONB NOT NULL, -- Target CPA, ROAS, CTR, etc.
  constraints JSONB DEFAULT '{}', -- Min/max bid limits, budget constraints
  is_active BOOLEAN DEFAULT true,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  last_used_at TIMESTAMP WITH TIME ZONE,
  usage_count INTEGER DEFAULT 0,
  average_performance JSONB DEFAULT '{}', -- Historical performance metrics
  
  UNIQUE(tenant_id, strategy_name)
);

-- Automation Execution Logs Table
-- Track all automation executions and results
CREATE TABLE IF NOT EXISTS automation_execution_logs (
  id SERIAL PRIMARY KEY,
  tenant_id VARCHAR(100) NOT NULL,
  automation_id VARCHAR(100) NOT NULL, -- Can be rule_id, strategy_id, or 'suite'
  automation_type VARCHAR(50) NOT NULL,
  activity_type VARCHAR(50) NOT NULL, -- 'executed', 'failed', 'created', 'modified'
  execution_status VARCHAR(20) DEFAULT 'pending', -- 'pending', 'running', 'completed', 'failed'
  metadata JSONB DEFAULT '{}', -- Execution details, results, errors
  execution_duration INTEGER, -- Milliseconds
  executed_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  completed_at TIMESTAMP WITH TIME ZONE,
  
  INDEX (tenant_id, executed_at),
  INDEX (automation_id, executed_at),
  INDEX (automation_type, executed_at)
);

-- Bid Adjustment History Table
-- Track all automated bid changes for audit and rollback
CREATE TABLE IF NOT EXISTS bid_adjustment_history (
  id SERIAL PRIMARY KEY,
  tenant_id VARCHAR(100) NOT NULL,
  campaign_id VARCHAR(100) NOT NULL,
  ad_group_id VARCHAR(100),
  keyword_id VARCHAR(100),
  adjustment_type VARCHAR(30) NOT NULL, -- 'bid_multiplier', 'bid_amount', 'budget_change'
  old_value DECIMAL(10,2),
  new_value DECIMAL(10,2),
  adjustment_reason TEXT,
  automation_rule_id INTEGER REFERENCES automation_rules(id),
  bid_strategy_id INTEGER REFERENCES custom_bid_strategies(id),
  performance_data JSONB DEFAULT '{}', -- Performance metrics at time of change
  estimated_impact JSONB DEFAULT '{}', -- Predicted impact of the change
  actual_impact JSONB DEFAULT '{}', -- Measured impact after change (populated later)
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  measured_at TIMESTAMP WITH TIME ZONE -- When actual impact was measured
);

-- Automation Performance Metrics Table
-- Track the effectiveness of different automation strategies
CREATE TABLE IF NOT EXISTS automation_performance_metrics (
  id SERIAL PRIMARY KEY,
  tenant_id VARCHAR(100) NOT NULL,
  automation_type VARCHAR(50) NOT NULL,
  automation_id INTEGER, -- References automation_rules.id or custom_bid_strategies.id
  metric_date DATE NOT NULL,
  campaigns_optimized INTEGER DEFAULT 0,
  total_adjustments INTEGER DEFAULT 0,
  cost_savings DECIMAL(10,2) DEFAULT 0,
  conversion_increase DECIMAL(8,4) DEFAULT 0,
  roas_improvement DECIMAL(6,4) DEFAULT 0,
  click_increase DECIMAL(8,4) DEFAULT 0,
  ctr_improvement DECIMAL(6,4) DEFAULT 0,
  quality_score_improvement DECIMAL(4,2) DEFAULT 0,
  execution_time_ms INTEGER DEFAULT 0,
  success_rate DECIMAL(4,2) DEFAULT 0, -- Percentage of successful optimizations
  confidence_score DECIMAL(3,2) DEFAULT 0, -- Algorithm confidence in changes
  rollback_rate DECIMAL(4,2) DEFAULT 0, -- Percentage of changes that were rolled back
  
  UNIQUE(tenant_id, automation_type, automation_id, metric_date)
);

-- Automation Alerts Table
-- Store alerts generated by automation systems
CREATE TABLE IF NOT EXISTS automation_alerts (
  id SERIAL PRIMARY KEY,
  tenant_id VARCHAR(100) NOT NULL,
  alert_type VARCHAR(30) NOT NULL, -- 'performance_drop', 'budget_exceeded', 'optimization_failed', etc.
  severity VARCHAR(10) NOT NULL, -- 'low', 'medium', 'high', 'critical'
  title VARCHAR(200) NOT NULL,
  message TEXT NOT NULL,
  automation_context JSONB DEFAULT '{}', -- Related automation rules, campaigns, etc.
  recommended_actions JSONB DEFAULT '{}', -- Suggested fixes or optimizations
  is_resolved BOOLEAN DEFAULT false,
  resolved_at TIMESTAMP WITH TIME ZONE,
  resolved_by VARCHAR(100), -- User ID or 'system'
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  
  INDEX (tenant_id, created_at),
  INDEX (tenant_id, is_resolved, created_at),
  INDEX (severity, created_at)
);

