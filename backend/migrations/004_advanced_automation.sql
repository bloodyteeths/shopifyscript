-- Function to calculate automation ROI
CREATE OR REPLACE FUNCTION calculate_automation_roi(
  tenant_id_param TEXT,
  automation_type_param TEXT,
  start_date DATE,
  end_date DATE
) RETURNS TABLE (
  automation_type TEXT,
  total_cost_savings DECIMAL,
  total_conversion_increase DECIMAL,
  total_roas_improvement DECIMAL,
  roi_percentage DECIMAL,
  confidence_score DECIMAL
) AS $$
BEGIN
  RETURN QUERY
  SELECT 
    apm.automation_type,
    SUM(apm.cost_savings) as total_cost_savings,
    SUM(apm.conversion_increase) as total_conversion_increase,
    AVG(apm.roas_improvement) as total_roas_improvement,
    (SUM(apm.cost_savings) / NULLIF(SUM(apm.cost_savings) * 0.1, 0)) * 100 as roi_percentage,
    AVG(apm.confidence_score) as confidence_score
  FROM automation_performance_metrics apm
  WHERE apm.tenant_id = tenant_id_param
    AND (automation_type_param IS NULL OR apm.automation_type = automation_type_param)
    AND apm.metric_date BETWEEN start_date AND end_date
  GROUP BY apm.automation_type;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to get automation health status
CREATE OR REPLACE FUNCTION get_automation_health_status(tenant_id_param TEXT)
RETURNS TABLE (
  total_active_rules INTEGER,
  total_executions_last_7d INTEGER,
  average_success_rate DECIMAL,
  total_cost_savings_last_30d DECIMAL,
  performance_grade CHAR(1)
) AS $$
DECLARE
  health_grade CHAR(1);
  success_rate DECIMAL;
  cost_savings DECIMAL;
BEGIN
  -- Get basic stats
  SELECT 
    COUNT(*) FILTER (WHERE is_active = true),
    COUNT(*) FILTER (WHERE last_executed_at >= NOW() - INTERVAL '7 days'),
    AVG(COALESCE((metadata->>'success_rate')::DECIMAL, 0))
  INTO total_active_rules, total_executions_last_7d, success_rate
  FROM automation_rules ar
  LEFT JOIN automation_execution_logs ael ON ar.id::TEXT = ael.automation_id
  WHERE ar.tenant_id = tenant_id_param;
  
  -- Get cost savings
  SELECT COALESCE(SUM(cost_savings), 0)
  INTO cost_savings
  FROM automation_performance_metrics
  WHERE tenant_id = tenant_id_param 
    AND metric_date >= CURRENT_DATE - INTERVAL '30 days';
  
  -- Calculate health grade
  IF success_rate >= 0.9 AND cost_savings >= 500 THEN
    health_grade := 'A';
  ELSIF success_rate >= 0.8 AND cost_savings >= 250 THEN
    health_grade := 'B';
  ELSIF success_rate >= 0.7 AND cost_savings >= 100 THEN
    health_grade := 'C';
  ELSIF success_rate >= 0.5 THEN
    health_grade := 'D';
  ELSE
    health_grade := 'F';
  END IF;
  
  RETURN QUERY SELECT 
    total_active_rules,
    total_executions_last_7d,
    success_rate as average_success_rate,
    cost_savings as total_cost_savings_last_30d,
    health_grade as performance_grade;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

